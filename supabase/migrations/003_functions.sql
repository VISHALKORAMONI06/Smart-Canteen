-- ---------------------------------------------------------------------------
-- HELPER: Get business date in Asia/Kolkata timezone
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.get_business_date()
RETURNS DATE LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public
AS $$
  SELECT (NOW() AT TIME ZONE 'Asia/Kolkata')::DATE;
$$;

-- ---------------------------------------------------------------------------
-- HELPER: Allocate next daily token atomically
-- Uses SELECT FOR UPDATE to lock the counter row, preventing races.
-- Creates the row for today if it doesn't exist.
-- Returns the token string, e.g. 'SC-101'
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.allocate_daily_token(p_date DATE)
RETURNS TEXT LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_counter INTEGER;
  v_token   TEXT;
BEGIN
  -- Upsert today's counter row, then lock it for update
  INSERT INTO public.daily_token_counters (business_date, counter)
  VALUES (p_date, 100)
  ON CONFLICT (business_date) DO NOTHING;

  -- Lock the row to prevent concurrent token allocation
  SELECT counter INTO v_counter
  FROM public.daily_token_counters
  WHERE business_date = p_date
  FOR UPDATE;

  -- Increment
  v_counter := v_counter + 1;
  v_token   := 'SC-' || v_counter::TEXT;

  -- Save incremented counter
  UPDATE public.daily_token_counters
  SET counter = v_counter
  WHERE business_date = p_date;

  RETURN v_token;
END;
$$;

-- ---------------------------------------------------------------------------
-- MAIN RPC: place_order
-- Called by the frontend with cart items and an idempotency key.
-- Validates everything server-side; never trusts client prices or totals.
--
-- Input: cart_items JSONB array of {menu_item_id, quantity}
--        student_note TEXT
--        idempotency_key TEXT (UUID generated by client)
--
-- Returns: JSONB with order details, token, estimated_pickup
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.place_order(
  p_cart_items     JSONB,
  p_student_note   TEXT DEFAULT '',
  p_idempotency_key TEXT DEFAULT NULL
)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_student_id       UUID;
  v_student_role     TEXT;
  v_settings         RECORD;
  v_business_date    DATE;
  v_canteen_now_time TIME;
  v_cart_item        JSONB;
  v_menu_item        RECORD;
  v_items_data       JSONB := '[]'::JSONB;
  v_subtotal_paise   INTEGER := 0;
  v_max_prep_mins    INTEGER := 5;
  v_token            TEXT;
  v_order_id         UUID;
  v_estimated_pickup TIMESTAMPTZ;
  v_idem_key         TEXT;
  v_existing_order   RECORD;
  v_quantity         INTEGER;
  v_item_id          UUID;
  v_line_total       INTEGER;
BEGIN
  -- 1. Validate authenticated user
  v_student_id := auth.uid();
  IF v_student_id IS NULL THEN
    RAISE EXCEPTION 'UNAUTHENTICATED: You must be signed in to place an order.';
  END IF;

  -- 2. Check student role (students only; staff don't place orders)
  SELECT role INTO v_student_role
  FROM public.profiles WHERE id = v_student_id;

  IF v_student_role NOT IN ('student', 'admin') THEN
    RAISE EXCEPTION 'FORBIDDEN: Only students can place orders.';
  END IF;

  -- 3. Load operational settings
  SELECT * INTO v_settings FROM public.app_settings WHERE id = 1;

  -- 4. Check canteen is accepting orders
  IF NOT v_settings.ordering_open THEN
    RAISE EXCEPTION 'CANTEEN_CLOSED: The canteen is not accepting orders at this time.';
  END IF;

  -- 5. Check business hours (Asia/Kolkata)
  v_canteen_now_time := (NOW() AT TIME ZONE v_settings.business_timezone)::TIME;
  v_business_date    := (NOW() AT TIME ZONE v_settings.business_timezone)::DATE;

  IF v_canteen_now_time < v_settings.opening_time OR v_canteen_now_time > v_settings.closing_time THEN
    RAISE EXCEPTION 'OUTSIDE_HOURS: Canteen ordering is only available between % and %.',
      v_settings.opening_time, v_settings.closing_time;
  END IF;

  -- 6. Validate cart is not empty
  IF p_cart_items IS NULL OR jsonb_array_length(p_cart_items) = 0 THEN
    RAISE EXCEPTION 'EMPTY_CART: Cannot place an order with an empty cart.';
  END IF;

  -- 7. Validate cart size
  IF jsonb_array_length(p_cart_items) > v_settings.max_items_per_order THEN
    RAISE EXCEPTION 'TOO_MANY_ITEMS: Cart exceeds maximum of % distinct items.', v_settings.max_items_per_order;
  END IF;

  -- 8. Handle idempotency — if this key already exists, return the existing order
  v_idem_key := COALESCE(p_idempotency_key, gen_random_uuid()::TEXT);

  SELECT * INTO v_existing_order
  FROM public.orders
  WHERE idempotency_key = v_idem_key;

  IF FOUND THEN
    -- Return existing order (idempotent retry)
    RETURN jsonb_build_object(
      'order_id',         v_existing_order.id,
      'token',            v_existing_order.token,
      'status',           v_existing_order.status,
      'total_paise',      v_existing_order.total_paise,
      'estimated_pickup', v_existing_order.estimated_pickup,
      'created_at',       v_existing_order.created_at,
      'idempotent_replay', TRUE
    );
  END IF;

  -- 9. Validate each cart item and fetch authoritative server prices
  FOR v_cart_item IN SELECT * FROM jsonb_array_elements(p_cart_items)
  LOOP
    v_item_id  := (v_cart_item->>'menu_item_id')::UUID;
    v_quantity := (v_cart_item->>'quantity')::INTEGER;

    -- Validate quantity
    IF v_quantity IS NULL OR v_quantity < 1 THEN
      RAISE EXCEPTION 'INVALID_QUANTITY: Quantity must be at least 1 for each item.';
    END IF;
    IF v_quantity > v_settings.max_qty_per_item THEN
      RAISE EXCEPTION 'QTY_EXCEEDED: Quantity % exceeds maximum of % per item.', v_quantity, v_settings.max_qty_per_item;
    END IF;

    -- Fetch menu item (authoritative data)
    SELECT * INTO v_menu_item
    FROM public.menu_items
    WHERE id = v_item_id
      AND active = TRUE
      AND archived_at IS NULL;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'ITEM_NOT_FOUND: Menu item % does not exist or has been removed.', v_item_id;
    END IF;

    IF NOT v_menu_item.available THEN
      RAISE EXCEPTION 'ITEM_UNAVAILABLE: "%" is currently sold out. Please remove it from your cart.', v_menu_item.name;
    END IF;

    -- Compute line total using SERVER price
    v_line_total     := v_menu_item.price_paise * v_quantity;
    v_subtotal_paise := v_subtotal_paise + v_line_total;

    -- Track max prep time for pickup estimate
    IF v_menu_item.prep_time_mins > v_max_prep_mins THEN
      v_max_prep_mins := v_menu_item.prep_time_mins;
    END IF;

    -- Append to items data
    v_items_data := v_items_data || jsonb_build_object(
      'menu_item_id',   v_item_id,
      'item_name',      v_menu_item.name,
      'unit_price_paise', v_menu_item.price_paise,
      'quantity',       v_quantity,
      'prep_time_mins', v_menu_item.prep_time_mins,
      'line_total_paise', v_line_total
    );
  END LOOP;

  -- 10. Calculate estimated pickup time:
  -- NOW() + max_prep_time + 5 min queue buffer, rounded up to next 5 min
  v_estimated_pickup := date_trunc('minute', NOW())
    + ((v_max_prep_mins + 5) || ' minutes')::INTERVAL;
  -- Round up to next 5 minutes
  v_estimated_pickup := date_trunc('minute', v_estimated_pickup)
    + CASE
        WHEN EXTRACT(MINUTE FROM v_estimated_pickup)::INTEGER % 5 = 0 THEN '0 minutes'::INTERVAL
        ELSE ((5 - EXTRACT(MINUTE FROM v_estimated_pickup)::INTEGER % 5) || ' minutes')::INTERVAL
      END;

  -- 11. Allocate unique daily token (atomic, with row-level lock)
  v_token := public.allocate_daily_token(v_business_date);

  -- 12. Create the order record
  v_order_id := gen_random_uuid();

  INSERT INTO public.orders (
    id, student_id, token, business_date, status,
    subtotal_paise, total_paise, student_note,
    estimated_pickup, idempotency_key, created_at, updated_at
  ) VALUES (
    v_order_id, v_student_id, v_token, v_business_date, 'Placed',
    v_subtotal_paise, v_subtotal_paise, -- no tax/discount in this version
    LEFT(COALESCE(p_student_note, ''), 200),
    v_estimated_pickup, v_idem_key, NOW(), NOW()
  );

  -- 13. Create order item snapshots
  INSERT INTO public.order_items (
    id, order_id, menu_item_id, item_name,
    unit_price_paise, quantity, prep_time_mins, line_total_paise
  )
  SELECT
    gen_random_uuid(),
    v_order_id,
    (item->>'menu_item_id')::UUID,
    item->>'item_name',
    (item->>'unit_price_paise')::INTEGER,
    (item->>'quantity')::INTEGER,
    (item->>'prep_time_mins')::INTEGER,
    (item->>'line_total_paise')::INTEGER
  FROM jsonb_array_elements(v_items_data) AS item;

  -- 14. Write audit log
  INSERT INTO public.audit_logs (actor_id, action, entity_type, entity_id, metadata)
  VALUES (
    v_student_id,
    'order.placed',
    'order',
    v_order_id::TEXT,
    jsonb_build_object(
      'token', v_token,
      'total_paise', v_subtotal_paise,
      'item_count', jsonb_array_length(v_items_data)
    )
  );

  -- 15. Return confirmed order details
  RETURN jsonb_build_object(
    'order_id',         v_order_id,
    'token',            v_token,
    'status',           'Placed',
    'total_paise',      v_subtotal_paise,
    'estimated_pickup', v_estimated_pickup,
    'created_at',       NOW(),
    'business_date',    v_business_date,
    'idempotent_replay', FALSE
  );

EXCEPTION
  WHEN unique_violation THEN
    -- Concurrent duplicate submission — return error for the losing request
    RAISE EXCEPTION 'DUPLICATE_ORDER: An order with this idempotency key already exists. Please refresh and try again.';
END;
$$;

-- ---------------------------------------------------------------------------
-- RPC: transition_order_status
-- Staff-only. Validates transition, records timestamp, writes audit log.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.transition_order_status(
  p_order_id     UUID,
  p_new_status   TEXT
)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor_id     UUID;
  v_actor_role   TEXT;
  v_order        RECORD;
  v_allowed      TEXT[];
BEGIN
  -- 1. Authentication check
  v_actor_id := auth.uid();
  IF v_actor_id IS NULL THEN
    RAISE EXCEPTION 'UNAUTHENTICATED: You must be signed in.';
  END IF;

  -- 2. Role check — only staff or admin
  SELECT role INTO v_actor_role FROM public.profiles WHERE id = v_actor_id;
  IF v_actor_role NOT IN ('staff', 'admin') THEN
    RAISE EXCEPTION 'FORBIDDEN: Only staff can update order status.';
  END IF;

  -- 3. Validate new status value
  IF p_new_status NOT IN ('Preparing', 'Ready', 'Collected', 'Cancelled') THEN
    RAISE EXCEPTION 'INVALID_STATUS: "%" is not a valid target status.', p_new_status;
  END IF;

  -- 4. Fetch order with lock
  SELECT * INTO v_order
  FROM public.orders
  WHERE id = p_order_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'ORDER_NOT_FOUND: Order % does not exist.', p_order_id;
  END IF;

  -- 5. Validate state machine transition
  v_allowed := CASE v_order.status
    WHEN 'Placed'    THEN ARRAY['Preparing', 'Cancelled']
    WHEN 'Preparing' THEN ARRAY['Ready']
    WHEN 'Ready'     THEN ARRAY['Collected']
    ELSE             ARRAY[]::TEXT[]
  END;

  IF NOT (p_new_status = ANY(v_allowed)) THEN
    RAISE EXCEPTION 'INVALID_TRANSITION: Cannot move order from % to %.', v_order.status, p_new_status;
  END IF;

  -- 6. Update the order with appropriate timestamp fields
  UPDATE public.orders
  SET
    status       = p_new_status,
    updated_by   = v_actor_id,
    preparing_at = CASE WHEN p_new_status = 'Preparing' THEN NOW() ELSE preparing_at END,
    ready_at     = CASE WHEN p_new_status = 'Ready'     THEN NOW() ELSE ready_at END,
    collected_at = CASE WHEN p_new_status = 'Collected' THEN NOW() ELSE collected_at END,
    cancelled_at = CASE WHEN p_new_status = 'Cancelled' THEN NOW() ELSE cancelled_at END,
    cancelled_by = CASE WHEN p_new_status = 'Cancelled' THEN v_actor_id ELSE cancelled_by END
  WHERE id = p_order_id;

  -- 7. Write audit log
  INSERT INTO public.audit_logs (actor_id, action, entity_type, entity_id, metadata)
  VALUES (
    v_actor_id,
    'order.status_changed',
    'order',
    p_order_id::TEXT,
    jsonb_build_object(
      'from_status', v_order.status,
      'to_status',   p_new_status,
      'token',       v_order.token
    )
  );

  RETURN jsonb_build_object(
    'order_id',   p_order_id,
    'old_status', v_order.status,
    'new_status', p_new_status,
    'updated_by', v_actor_id,
    'updated_at', NOW()
  );
END;
$$;

-- ---------------------------------------------------------------------------
-- RPC: update_buffer_rate (admin/staff only)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.update_buffer_rate(p_rate NUMERIC)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor_id   UUID;
  v_actor_role TEXT;
  v_bounded    NUMERIC;
BEGIN
  v_actor_id := auth.uid();
  IF v_actor_id IS NULL THEN
    RAISE EXCEPTION 'UNAUTHENTICATED';
  END IF;

  SELECT role INTO v_actor_role FROM public.profiles WHERE id = v_actor_id;
  IF v_actor_role NOT IN ('staff', 'admin') THEN
    RAISE EXCEPTION 'FORBIDDEN: Only staff or admin can update buffer rate.';
  END IF;

  v_bounded := GREATEST(0, LEAST(0.5, p_rate));

  UPDATE public.app_settings
  SET buffer_rate = v_bounded, updated_by = v_actor_id
  WHERE id = 1;

  RETURN jsonb_build_object('buffer_rate', v_bounded);
END;
$$;

-- ---------------------------------------------------------------------------
-- RPC: update_item_availability (staff/admin only)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.update_item_availability(
  p_item_id  UUID,
  p_available BOOLEAN
)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor_id   UUID;
  v_actor_role TEXT;
  v_item       RECORD;
BEGIN
  v_actor_id := auth.uid();
  IF v_actor_id IS NULL THEN
    RAISE EXCEPTION 'UNAUTHENTICATED';
  END IF;

  SELECT role INTO v_actor_role FROM public.profiles WHERE id = v_actor_id;
  IF v_actor_role NOT IN ('staff', 'admin') THEN
    RAISE EXCEPTION 'FORBIDDEN: Only staff or admin can change item availability.';
  END IF;

  UPDATE public.menu_items
  SET available = p_available
  WHERE id = p_item_id AND active = TRUE AND archived_at IS NULL
  RETURNING * INTO v_item;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'ITEM_NOT_FOUND: Menu item % not found or already archived.', p_item_id;
  END IF;

  INSERT INTO public.audit_logs (actor_id, action, entity_type, entity_id, metadata)
  VALUES (
    v_actor_id,
    'menu.availability_changed',
    'menu_item',
    p_item_id::TEXT,
    jsonb_build_object('available', p_available, 'name', v_item.name)
  );

  RETURN jsonb_build_object(
    'id',        v_item.id,
    'name',      v_item.name,
    'available', v_item.available
  );
END;
$$;

-- ---------------------------------------------------------------------------
-- RPC: update_ordering_open (admin only)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.update_ordering_open(p_open BOOLEAN)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor_id   UUID;
  v_actor_role TEXT;
BEGIN
  v_actor_id := auth.uid();
  IF v_actor_id IS NULL THEN RAISE EXCEPTION 'UNAUTHENTICATED'; END IF;

  SELECT role INTO v_actor_role FROM public.profiles WHERE id = v_actor_id;
  IF v_actor_role != 'admin' THEN
    RAISE EXCEPTION 'FORBIDDEN: Only admins can toggle canteen ordering state.';
  END IF;

  UPDATE public.app_settings SET ordering_open = p_open WHERE id = 1;

  INSERT INTO public.audit_logs (actor_id, action, entity_type, entity_id, metadata)
  VALUES (v_actor_id, 'settings.ordering_open_changed', 'settings', '1', jsonb_build_object('ordering_open', p_open));

  RETURN jsonb_build_object('ordering_open', p_open);
END;
$$;

-- ---------------------------------------------------------------------------
-- RPC: get_demand_metrics (staff/admin only)
-- Returns aggregated demand for a given business date
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.get_demand_metrics(p_date DATE DEFAULT NULL)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor_id   UUID;
  v_actor_role TEXT;
  v_date       DATE;
  v_result     JSONB;
BEGIN
  v_actor_id := auth.uid();
  IF v_actor_id IS NULL THEN RAISE EXCEPTION 'UNAUTHENTICATED'; END IF;

  SELECT role INTO v_actor_role FROM public.profiles WHERE id = v_actor_id;
  IF v_actor_role NOT IN ('staff', 'admin') THEN
    RAISE EXCEPTION 'FORBIDDEN: Only staff or admin can view demand metrics.';
  END IF;

  v_date := COALESCE(p_date, public.get_business_date());

  SELECT jsonb_build_object(
    'business_date', v_date,
    'total_orders',  COUNT(DISTINCT o.id),
    'active_orders', COUNT(DISTINCT o.id) FILTER (WHERE o.status IN ('Placed','Preparing','Ready')),
    'order_value_paise', COALESCE(SUM(o.total_paise) FILTER (WHERE o.status != 'Cancelled'), 0),
    'item_demand', (
      SELECT jsonb_agg(
        jsonb_build_object(
          'menu_item_id', oi.menu_item_id,
          'item_name',    oi.item_name,
          'total_ordered', SUM(oi.quantity),
          'pending_to_cook', SUM(oi.quantity) FILTER (WHERE o2.status = 'Placed')
        )
      )
      FROM public.order_items oi
      JOIN public.orders o2 ON o2.id = oi.order_id
      WHERE o2.business_date = v_date
        AND o2.status NOT IN ('Cancelled', 'Expired')
      GROUP BY oi.menu_item_id, oi.item_name
    )
  )
  INTO v_result
  FROM public.orders o
  WHERE o.business_date = v_date
    AND o.status NOT IN ('Cancelled', 'Expired');

  RETURN v_result;
END;
$$;
